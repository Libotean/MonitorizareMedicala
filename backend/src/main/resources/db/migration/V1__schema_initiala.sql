CREATE TABLE utilizator (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email    VARCHAR(150) NOT NULL UNIQUE,
    parola   VARCHAR(100) NOT NULL,
    rol      VARCHAR(20)  NOT NULL CHECK (rol IN ('PACIENT', 'MEDIC', 'ADMIN')),
    creat_la TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pacient (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilizator_id  BIGINT       NOT NULL UNIQUE REFERENCES utilizator (id),
    nume           VARCHAR(100) NOT NULL,
    prenume        VARCHAR(100) NOT NULL,
    data_nasterii  DATE         NOT NULL
);

CREATE TABLE medic (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilizator_id  BIGINT       NOT NULL UNIQUE REFERENCES utilizator (id),
    nume           VARCHAR(100) NOT NULL,
    prenume        VARCHAR(100) NOT NULL,
    specializare   VARCHAR(100) NOT NULL
);

-- N-N: un medic urmareste mai multi pacienti, un pacient poate avea mai multi medici
CREATE TABLE medic_pacient (
    medic_id   BIGINT NOT NULL REFERENCES medic (id)   ON DELETE CASCADE,
    pacient_id BIGINT NOT NULL REFERENCES pacient (id) ON DELETE CASCADE,
    PRIMARY KEY (medic_id, pacient_id)
);

CREATE TABLE masuratoare (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pacient_id          BIGINT       NOT NULL REFERENCES pacient (id),
    puls                INTEGER      CHECK (puls > 0),
    tensiune_sistolica  INTEGER      CHECK (tensiune_sistolica > 0),
    tensiune_diastolica INTEGER      CHECK (tensiune_diastolica > 0),
    temperatura         NUMERIC(4,1),
    glicemie            INTEGER      CHECK (glicemie > 0),
    masurat_la          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE alerta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    masuratoare_id  BIGINT       NOT NULL REFERENCES masuratoare (id),
    tip             VARCHAR(20)  NOT NULL CHECK (tip IN ('PULS', 'TENSIUNE', 'TEMPERATURA', 'GLICEMIE')),
    mesaj           VARCHAR(255) NOT NULL,
    citita          BOOLEAN      NOT NULL DEFAULT FALSE,
    creat_la        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_masuratoare_pacient ON masuratoare (pacient_id, masurat_la);
CREATE INDEX idx_alerta_masuratoare  ON alerta (masuratoare_id);
CREATE INDEX idx_medic_pacient_pacient ON medic_pacient (pacient_id);
